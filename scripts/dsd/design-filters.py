#!/usr/bin/env python3 -I
"""Writes audio/Decode/VibeDSDFilterTaps.h, the DSD to PCM filters.

docs/dsd-to-pcm.md has the measurements behind each choice. Run it with
`python3 -I scripts/dsd/design-filters.py` from the repo root. It needs
NumPy and SciPy. The rates below are DSD64's. Each filter scales with the
DSD rate, so the 48 kHz family's rates take the same taps.
"""

import pathlib
import sys

import numpy as np
from scipy import signal

DSD64 = 2822400.0
FIRST = 352800.0  # the first stage's output rate
OUTPUT = 176400.0
PASS = 40000.0
# The first stage folds 264.6 kHz and up onto 0 to 88.2 kHz, the band the
# second stage keeps.
FIRST_STOP = FIRST - OUTPUT / 2
SECOND_TAPS = 97


def first_stage(multiple):
    rate = DSD64 * multiple
    taps = signal.remez(96 * multiple, [0, PASS, FIRST_STOP, rate / 2], [1, 0],
                        weight=[1, 100], fs=rate, maxiter=400)
    return taps / taps.sum()


def second_stage():
    taps = signal.remez(SECOND_TAPS, [0, PASS, OUTPUT / 2, FIRST / 2], [1, 0], fs=FIRST, maxiter=400)
    return taps / taps.sum()


def table(name, taps):
    rows = ",\n".join("    " + ", ".join(f"{t:.17g}" for t in taps[i:i + 4]) for i in range(0, len(taps), 4))
    return f"static const double {name}[{len(taps)}] = {{\n{rows},\n}};\n"


def main():
    out = pathlib.Path(__file__).resolve().parents[2] / "audio/Decode/VibeDSDFilterTaps.h"
    parts = [
        "//\n//  VibeDSDFilterTaps.h\n//  vibe-libs\n//\n"
        "//  Generated by scripts/dsd/design-filters.py. Do not edit. docs/dsd-to-pcm.md\n"
        "//  has the measurements behind them.\n//\n\n#pragma once\n\n",
        "// The first stage, a tap per DSD bit, for DSD64, 128, 256, and 512: equiripple,\n"
        "// flat to 40 kHz, and stopped from 264.6 kHz, at DSD64's rates.\n",
    ]
    for multiple in (1, 2, 4, 8):
        parts.append(table(f"kVibeDSDFirstStage{multiple}", first_stage(multiple)))
    parts.append("\n// The second stage, at 352.8 kHz: flat to 40 kHz, and stopped from 88.2 kHz.\n")
    parts.append(table("kVibeDSDSecondStage", second_stage()))
    out.write_text("".join(parts))
    print(f"wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
